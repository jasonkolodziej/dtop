//! The built-in themes, generated from the Swift sources (all palettes are original to dtop).

use crate::color::Color;
use crate::theme::{Role, Theme};
use crate::widgets::BorderCharacters;

fn theme(name: &str, colors: &[(Role, Color)], border: BorderCharacters) -> Theme {
    let mut theme = Theme::blank(name);
    for (role, color) in colors {
        theme.colors.insert(*role, *color);
    }
    theme.border = border;
    theme
}

